async def seed_system_excuses(session: AsyncSession) -> int:
    """Seed initial system excuses if they do not exist."""
    count = 0
    for category, texts in SYSTEM_EXCUSES.items():
        for text in texts:
            stmt = select(Excuse).where(
                Excuse.text == text,
                Excuse.is_system.is_(True),
                Excuse.deleted_at.is_(None),
            )
            result = await session.execute(stmt)
            if result.scalar_one_or_none() is None:
                excuse = Excuse(
                    text=text,
                    category=category.value,
                    is_system=True,
                    user_id=None,
                )
                session.add(excuse)
                count += 1
    if count > 0:
        await session.commit()
    return count
